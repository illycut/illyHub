/**
 * Pandora Sync via the hub Mac's AirPlay bridge (Phase 7, PRD PAN-4, experimental). Pure view
 * logic so the picker, Now Playing, the mini-player and Settings agree.
 *
 * Facts baked in (docs/api.md "AirPlay bridge and Pandora Sync", docs/prd-review.md §5): the hub
 * Mac plays Pandora itself and streams to AirPlay 2 outputs; the hub only manages the routing and
 * never controls that playback, so transport and seek for the bridged rooms are off (their volume
 * still works). The app sends the chosen side ids; the hub matches rooms to outputs. Amber stays
 * reserved for Sync Play, which creates a live audio state the hub drives; this hands off to the
 * Mac, so its affordances are plain text. One name everywhere: "Pandora Sync" (§10).
 */
import messages from "./hub/messages.json";
import type { AirPlayInfo } from "./hub/library";
import type { HubState, PandoraSyncState } from "./hub/types";
import { joinRooms } from "./sync";

/**
 * The hub owns copy where it exports it (`templates.airplay.*` in messages.json, regenerated by
 * `npm run openapi`); the second key is the hub's older spelling; the fallback is the client's.
 */
function hubMessage(keys: string[], fallback: string): string {
  const templates = (messages as { templates?: Record<string, unknown> }).templates ?? {};
  const airplay = templates.airplay && typeof templates.airplay === "object" ? (templates.airplay as Record<string, unknown>) : {};
  for (const k of keys) {
    const v = airplay[k];
    if (typeof v === "string" && v.trim()) return v;
  }
  return fallback;
}

