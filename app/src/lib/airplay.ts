/** Picker note tied to the button via aria-describedby (UX U1). */
export function pandoraSyncNote(roomNames: readonly string[]): string {
  const rooms = roomNames.length ? joinRooms([...roomNames]) : "your rooms";
  return `The hub Mac plays this station to ${rooms} over AirPlay. It opens Pandora there; press play on the Mac.`;
}

export function isPandoraSyncActive(state: HubState | null | undefined): boolean {
  return !!state?.pandora_sync?.active;
}

export function pandoraSync(state: HubState | null | undefined): PandoraSyncState | null {
  return state?.pandora_sync ?? null;
}

/**
 * Is this room under the bridge right now? Scoped to `side_ids`, so other rooms stay fully live.
 * A hub that reports `active` without `side_ids` (older shape) bridges every room.
 */
export function bridgedSide(sideId: string | null | undefined, ps: PandoraSyncState | null | undefined): boolean {
  if (!ps?.active || !sideId) return false;
  return ps.side_ids.length === 0 || ps.side_ids.includes(sideId);
}

/**
 * Picker rule: the affordance appears only for a Pandora station AND when the hub reports the
 * bridge available, and never while a Sync Play session is live (the hub refuses with
 * `sync_active`; the app hides the button first). Never for other content.
 */
export function pandoraSyncOffered(ref: { service: string; kind: string } | null | undefined, airplay: AirPlayInfo | null | undefined, syncActive = false): boolean {
  return !syncActive && ref?.service === "pandora" && ref.kind === "station" && !!airplay?.available;
}

/** Settings row line: "Available" / "Unavailable · {reason}" / "Off". */
export function airplayRowStatus(info: AirPlayInfo | null | undefined): string {
  if (!info?.enabled) return "Off";
  if (info.available) return "Available";
  return `Unavailable · ${info.reason?.trim() || AIRPLAY_NO_REASON}`;
}

/** Bridged room count for labels: the hub's `side_ids`, else its output names. */
function roomCount(ps: PandoraSyncState): number {
  return ps.side_ids.length || ps.outputs.length;
}

/** Room names for the indicator's accessible label: "Pandora Sync: Kitchen and Living Room Amp". */
export function pandoraSyncLabel(state: HubState | null | undefined, sides?: Record<string, { name: string }>): string | null {
  const ps = pandoraSync(state);
  if (!ps?.active) return null;
  const names = ps.side_ids.length && sides ? ps.side_ids.map((id) => sides[id]?.name ?? "another room") : ps.outputs;
  return names.length ? `${PANDORA_SYNC}: ${joinRooms(names)}` : PANDORA_SYNC;
}

/** Short header form that never wraps: "Pandora Sync · 2 rooms". */
export function pandoraSyncLabelShort(state: HubState | null | undefined): string | null {
  const ps = pandoraSync(state);
  if (!ps?.active) return null;
  const n = roomCount(ps);
  return n > 0 ? `${PANDORA_SYNC} · ${n} ${n === 1 ? "room" : "rooms"}` : PANDORA_SYNC;
}
